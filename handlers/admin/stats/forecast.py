"""База прогноза в сводке за день.

Чистая логика без aiogram и без базы: прогоняется синтетикой, не поднимая бота.

Исторически прогноз строился от дохода одного отчётного дня, умноженного на 7 и
на 30. На аномальном дне это завышало месяц в 2.6 раза (15.10.2026: 408 870 ₽
против среднего темпа около 155 000 ₽), на слабом — так же занижало. Режим
выбирается флагом «Прогноз по среднему» на экране режимов; выключенный флаг
оставляет прежнее поведение.
"""

#: Флаг в MODES_CONFIG. Выключен - прогноз от дохода дня, как было всегда.
FORECAST_AVG_MODE = "DAILY_FORECAST_AVG_ENABLED"

LABEL_DAY = "день"
LABEL_AVG = "ср. 14 дн."


def forecast_base(avg_mode, day_revenue: float, avg_revenue: float) -> tuple[float, str]:
    """База прогноза и подпись режима для заголовка блока.

    Подпись обязательна: без неё по числу не понять, от чего его считали.
    """
    if bool(avg_mode):
        return avg_revenue, LABEL_AVG
    return day_revenue, LABEL_DAY
