"""Прогноз в сводке за день: два режима.

Чистая логика без aiogram и без базы: прогоняется синтетикой, не поднимая бота.

Исторически прогноз строился от выручки одного отчётного дня, умноженной на 7 и
на 30: один день задавал оба горизонта, поэтому акция или выходной сдвигали
прогноз в разы. Проверка на годовом ряде показала, что эта методика худшая на
обоих горизонтах в каждом месяце без исключения.

Второй режим считает каждый горизонт по периоду такой же длины: неделю - по
последним семи дням, месяц - по последним тридцати. Число получается
проверяемым: это сумма фактических дней, а не экстраполяция.
"""

#: Флаг в MODES_CONFIG. Выключен - прежнее поведение, выручка дня × 7 и × 30.
FORECAST_AVG_MODE = "DAILY_FORECAST_AVG_ENABLED"

#: Горизонты в днях. Они же задают длину окна в скользящем режиме: окно равно
#: горизонту по определению, поэтому настраивать тут нечего.
WEEK_DAYS = 7
MONTH_DAYS = 30

LABEL_DAY = "день"
LABEL_ROLLING = "скольз."


def _window_sum(series, days: int) -> float:
    """Сумма последних `days` значений. Короткий ряд достраиваем средним.

    Без достройки молодая установка с историей в пять дней получала бы
    заниженный месяц: тридцатидневное окно складывало бы пять чисел.
    """
    if not series:
        return 0.0
    tail = list(series[-days:])
    total = sum(tail)
    if len(tail) < days:
        total += (total / len(tail)) * (days - len(tail))
    return total


def forecast(avg_mode, day_revenue: float, series) -> tuple[float, float, str]:
    """Прогноз недели, прогноз месяца и подпись режима для заголовка блока.

    Подпись обязательна: без неё по числу не понять, от чего его считали.
    """
    if bool(avg_mode):
        return (
            _window_sum(series, WEEK_DAYS),
            _window_sum(series, MONTH_DAYS),
            LABEL_ROLLING,
        )
    return day_revenue * WEEK_DAYS, day_revenue * MONTH_DAYS, LABEL_DAY
